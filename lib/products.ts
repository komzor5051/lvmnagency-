export type ProductBuy =
  | { kind: "lava"; url: string } // lava.top checkout; empty url = not configured yet (fallback to Telegram)
  | { kind: "lava-widget"; src: string } // lava.top embedded iframe pay button (widget.lava.top/<offerId>)
  | { kind: "form"; url: string } // lead form, e.g. /audit
  | { kind: "waitlist" }; // email collection (course)

export type ProductType = "consultation" | "digital" | "service" | "coming-soon";

export type ProductFaq = { q: string; a: string };

// "Что дальше" bridge to the next funnel step, rendered as a clickable tile
// on the product page. Clicks fire funnel_bridge_click {from, to}.
export type ProductNextStep = { slug: string; label: string; text: string };

// VSL-видео над описанием продукта. Хостинг любой — Kinescope, VK Video,
// YouTube: embedUrl это src для iframe. poster лежит в /public.
export type ProductVsl = {
  embedUrl: string;
  poster: string;
  title: string;
  ratio?: "16/9" | "9/16";
};

export type Product = {
  id: string;
  type: ProductType;
  title: string;
  tagline: string; // short card description
  description: string[]; // paragraphs for /products
  price: number | null; // null for coming-soon
  priceLabel: string; // "10 000 ₽", "от 50 000 ₽", "скоро"
  meta: string; // "1:1 · 60 минут · онлайн"
  buy: ProductBuy;
  // Готовый баннер вместо типографской плашки в витрине.
  // Пусто — рисуется .bento-cover из заголовка продукта.
  cover?: { src: string; width: number; height: number };
  vsl?: ProductVsl;
  faq?: ProductFaq[];
  // CTA labels: action + what you get, never bare "купи".
  cta?: { buy: string; fallback: string }; // buy = checkout configured; fallback = manual Telegram channel
  nextStep?: ProductNextStep; // funnel bridge to the next ladder step
};

