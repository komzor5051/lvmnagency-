async function ensureUniqueSlug(base: string): Promise<string> {
  let slug = base;
  for (let n = 2; ; n++) {
    const { data } = await supabase
      .from("lvmn_blog_posts")
      .select("id")
      .eq("slug", slug)
      .maybeSingle();
    if (!data) return slug;
    slug = `${base}-${n}`;
  }
}

async function main() {
  for (const article of ARTICLES) {
    const md = cleanMarkdown(article.md);
    const html = renderMarkdown(md);
    const slug = await ensureUniqueSlug(slugify(article.title));

    const { error } = await supabase.from("lvmn_blog_posts").insert({
      slug,
      title: article.title,
      meta_desc: article.metaDesc,
      content_md: md,
      content_html: html,
      cover_image: null,
      tags: article.tags,
      cta_url: "https://t.me/lyaminvl",
      status: "published",
      published_at: new Date().toISOString(),
    });

    if (error) {
      console.error(`Failed: "${article.title}":`, error.message);
    } else {
      console.log(`Published: /blog/${slug}`);
    }
  }
}

main().catch(console.error);
