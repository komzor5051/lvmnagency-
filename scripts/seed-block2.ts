async function ensureUniqueSlug(base: string): Promise<string> {
  let slug = base;
  for (let n = 2; ; n++) {
    const { data } = await supabase
      .from("lvmn_blog_posts")
      .select("id")
      .eq("slug", slug)
      .maybeSingle();
    if (!data) return slug;
    slug = `${base}-${n}`;
  }
}

